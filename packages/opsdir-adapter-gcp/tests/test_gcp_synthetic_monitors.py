"""Cloud Monitoring synthetic monitors rendered from the record: an oidc-token check and an LDAPS bind as Node.js Cloud
Run functions (source zipped into the binding's Cloud Storage location, credentials from Secret Manager, Direct VPC
egress for an internal service), the uptime checks running them, the runtime and build service accounts with their
grants; what can't run is named; the function source runs under Node.js."""
import json
import shutil
import subprocess

import pytest

from opsdir.core.contract import Endpoint
from opsdir.domains.observability.naming import CANARIES
from opsdir_format_terraform.hcl import as_text
from opsdir_adapter_gcp.synthetic_monitors import render_monitors
from network_fixtures import BETA, entry, model, rule

ENDPOINTS = (Endpoint("health", "/pf/heartbeat.ping", "web"), Endpoint("token", "/as/token.oauth2", "web"))
SECRET = "gcp-sm://projects/ciam-prod/secrets/canary-client"


def _canary(cn, **attrs):
    return entry(CANARIES, cn, "ciamCanary", **attrs).replace("objectClass: ciamCanary",
                                                               "objectClass: ciamObject\nobjectClass: ciamCanary")


TREE = (f"dn: {CANARIES}\nobjectClass: top\nobjectClass: organizationalUnit\nou: canaries\n",
        _canary("sso-alive", ciamCheckedService="sso", ciamCanaryFlow="health"),
        _canary("sso-token", ciamCheckedService="sso", ciamCanaryFlow="oidc-token", ciamUsesRole="client",
                ciamInterval="5m"),
        _canary("directory", ciamCheckedService="ldaps", ciamCanaryFlow="ldap-bind"))
BINDINGS = (entry(BETA, "svc-sso", "ciamServiceName", ciamBindingRole="sso", ciamFqdn="sso.example.test",
                  ciamTargetRole="web", ciamExposure="internet"),
            entry(BETA, "client", "ciamSecretRef", ciamBindingRole="client", ciamRefUri=SECRET),
            entry(BETA, "Token-Check", "ciamCanaryBinding", ciamBindingRole="canary-sso-token",
                  ciamRealizes="sso-token", ciamStorageRef="gs://ciam-checks/src/"),
            entry(BETA, "svc-ldaps", "ciamServiceName", ciamBindingRole="ldaps", ciamFqdn="ldap.example.test",
                  ciamPort="1636", ciamTargetRole="ds", ciamFrontendIp="10.1.1.100", ciamExposure="internal"),
            rule(BETA, "fw-web-ds", "10.1.2.0/24", "1636", "ds"),
            entry(BETA, "directory", "ciamCanaryBinding", ciamBindingRole="canary-directory",
                  ciamRealizes="directory", ciamStorageRef="gs://ciam-checks"))


def _render(bindings=BINDINGS):
    _, _, beta = model(beta=bindings, tree=TREE)
    hcl, files = as_text(render_monitors(beta, ENDPOINTS))
    return "\n".join(hcl), hcl, files


def test_a_token_check_is_a_node_function_run_by_a_synthetic_monitor():
    text, _, files = _render()
    assert 'resource "google_cloudfunctions2_function" "token_check" {' in text
    assert 'name        = "token-check"' in text
    assert 'runtime         = "nodejs24"' in text and 'entry_point     = "SyntheticFunction"' in text
    assert "service_account = google_service_account.checks_build.id" in text
    assert ('      key        = "CHECK_CREDENTIALS"\n      project_id = "ciam-prod"\n'
            '      secret     = "canary-client"\n      version    = "latest"') in text
    assert 'name   = "src/check-token-check.zip"' in text
    assert "generation = google_storage_bucket_object.check_token_check.generation" in text
    assert 'source_dir  = "${path.module}/checks/token-check"' in text
    assert ('  synthetic_monitor {\n    cloud_function_v2 {\n'
            '      name = google_cloudfunctions2_function.token_check.id') in text
    assert 'period       = "300s"' in text and 'timeout      = "60s"' in text and 'realizes    = "sso-token"' in text
    assert "sso-alive" not in text                                       # an uptime check's (canaries)
    package = json.loads(files["terraform/checks/token-check/package.json"])
    assert package["dependencies"] == {"@google-cloud/functions-framework": "^5.0.5",
                                       "@google-cloud/synthetics-sdk-api": "^0.7.0"}
    source = files["terraform/checks/token-check/index.js"]
    assert source.startswith("// Generated by opsdir from ") and 'const CHECK_FLOW = "oidc-token";' in source
    assert 'const CHECK_URL = "https://sso.example.test/as/token.oauth2";' in source


def test_an_internal_ldap_check_egresses_into_the_subnet_the_firewall_admits():
    text, _, files = _render()
    function = text[text.index('resource "google_cloudfunctions2_function" "directory"'):]
    function = function[:function.index("\n}\n")]
    assert ("    direct_vpc_network_interface {\n      network    = data.google_compute_network.main.self_link\n"
            "      subnetwork = data.google_compute_subnetwork.subnet_web.self_link\n    }\n"
            '    direct_vpc_egress = "VPC_EGRESS_PRIVATE_RANGES_ONLY"') in function
    assert "CHECK_CREDENTIALS" not in function                            # an anonymous bind
    assert 'const CHECK_URL = "ldaps://ldap.example.test:1636";' in files["terraform/checks/directory/index.js"]


def test_the_checks_accounts_hold_only_their_grants():
    text, _, _ = _render()
    assert 'account_id   = "ciam-prod-checks"' in text and 'account_id   = "ciam-prod-check-build"' in text
    assert 'role    = "roles/cloudtrace.agent"' in text
    assert ('resource "google_secret_manager_secret_iam_member" "checks_ciam_prod_canary_client" {\n'
            '  project   = "ciam-prod"\n  secret_id = "canary-client"\n'
            '  role      = "roles/secretmanager.secretAccessor"\n') in text
    assert ('resource "google_storage_bucket_iam_member" "checks_build_ciam_checks" {\n  bucket = "ciam-checks"\n'
            '  role   = "roles/storage.objectViewer"\n') in text
    assert text.count('resource "google_storage_bucket_iam_member"') == 1          # one source bucket
    assert '"roles/logging.logWriter"' in text and '"roles/artifactregistry.writer"' in text


def test_what_a_monitor_cant_run_is_named():
    bindings = tuple(b.replace(SECRET, "vault://secret/canary").replace("ciamStorageRef: gs://ciam-checks\n", "")
                     for b in BINDINGS)
    _, hcl, files = _render(bindings)
    assert sorted(hcl) == [
        "# NOTE: canary directory: not rendered: its canary binding directory records no Cloud Storage location for "
        "its function's source (ciamStorageRef gs://bucket/prefix)",
        "# NOTE: canary sso-token: not rendered: its credentials (client) aren't a global Secret Manager secret "
        "(gcp-sm://projects/<p>/secrets/<name>)"] and files == {}


@pytest.mark.skipif(not shutil.which("node"), reason="node")
def test_the_function_source_registers_its_handler_and_probes(tmp_path):
    _, _, files = _render()
    (tmp_path / "index.js").write_text(files["terraform/checks/directory/index.js"])
    stubs = {"@google-cloud/functions-framework": "exports.http = (name, fn) => { global.registered = [name, fn]; };",
             "@google-cloud/synthetics-sdk-api": "exports.runSyntheticHandler = (fn) => fn;"}
    for package, body in stubs.items():
        (tmp_path / "node_modules" / package).mkdir(parents=True)
        (tmp_path / "node_modules" / package / "index.js").write_text(body)
    run = subprocess.run(["node", "-e", """
        require("./index.js");
        const [name, handler] = global.registered;
        handler({logger: {info: (m) => console.log("INFO " + m)}}).then(() => console.log("PASSED"),
            (e) => console.log(name + " FAILED " + e.code));"""], cwd=tmp_path, capture_output=True, text=True,
                         timeout=60)
    assert run.stdout.strip() in ("SyntheticFunction FAILED ENOTFOUND", "SyntheticFunction FAILED EAI_AGAIN")


def test_monitors_read_back_from_state_as_canary_bindings_not_jobs():
    from opsdir_format_terraform.hcl import TfBlock, block
    from opsdir_adapter_gcp.inventory import state_resources
    from opsdir_adapter_gcp.rendered_state import rendered_states
    d, _, beta = model(beta=BINDINGS, tree=TREE)
    main = "\n\n".join((*as_text(render_monitors(beta, ENDPOINTS))[0],
                        block(*TfBlock("provider", ("google",), (("project", "ciam-prod"), ("region", "us-east4")))),
                        block("variable", ["project_id"], [("default", "ciam-prod")]),
                        block("variable", ["region"], [("default", "us-east4")])))
    (text,) = rendered_states({"beta/prod/main.tf": main}, d, "beta/prod").values()
    resources, _ = state_resources(text)
    canaries = {r.attrs["ciamRealizes"][0]: r for r in resources if r.kind == "canary"}
    assert canaries["sso-token"].attrs["ciamStorageRef"] == ("gs://ciam-checks/src",)
    assert canaries["directory"].attrs["ciamStorageRef"] == ("gs://ciam-checks",)
    assert (canaries["sso-token"].role, canaries["sso-token"].attrs["ciamInterval"]) == ("canary-sso-token", ("5m",))
    assert not [r for r in resources if r.kind == "job"]                 # a check's function isn't a job


def test_monitors_read_back_from_the_cli_inventory():
    from opsdir_adapter_gcp.cli import cli_resources
    p = "projects/ciam-prod"
    function = f"{p}/locations/us-east4/functions/token-check"
    files = {"functions.json": json.dumps([{
                 "name": function, "environment": "GEN_2", "labels": {"realizes": "sso-token"},
                 "buildConfig": {"runtime": "nodejs24", "source": {"storageSource": {
                     "bucket": "ciam-checks", "object": "src/check-token-check.zip"}}}}]),
             "monitoring.json": json.dumps([{"name": f"{p}/uptimeCheckConfigs/token", "displayName": "Token-Check",
                                             "period": "300s", "userLabels": {"realizes": "sso-token"},
                                             "syntheticMonitor": {"cloudFunctionV2": {"name": function}}}])}
    resources, _ = cli_resources(files)
    (canary,) = [r for r in resources if r.kind == "canary"]
    assert canary.attrs == {"ciamInterval": ("5m",), "ciamRealizes": ("sso-token",),
                            "ciamStorageRef": ("gs://ciam-checks/src",)}
    assert not [r for r in resources if r.kind == "job"]
