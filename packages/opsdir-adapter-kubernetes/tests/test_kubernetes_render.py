"""What the Kubernetes adapter renders around the workloads an environment runs on Kubernetes: per namespace a
kustomization of the namespace (its pod-security level), service accounts with the provider's workload identity
annotations, network policies from the products' listeners (pods of roles running here by label, servers' subnets
otherwise), and secret delivery: always the list of Secrets required and what delivers them; External Secrets
Operator stores and secrets, or CSI provider classes, when asked. Values never; UNBOUND where the record is silent."""
