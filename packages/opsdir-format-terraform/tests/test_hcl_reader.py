"""The HCL reader: what block() and hcl() write reads back as the data they were given, so block() writes it again
byte for byte; what the reader can't place is an error naming the line."""
import re

import pytest

from opsdir_format_terraform.hcl import (Block, TfBlock, TfFile, block, comment, hcl_file, hcl_item, jsonencoded, ref,
                                        tf_block, tf_import, written)
from opsdir_format_terraform.hcl_reader import read_hcl, value_of

BODY = (("name", "ciam-prod-am"), ("#", "a comment in the body"), ("vpc_id", ref("data.aws_vpc.main.id")),
        ("count", 2), ("weight", 0.5), ("enabled", True), ("escaped", 'say "hi" \\ bye'),
        ("depends_on", (ref("aws_iam_role.am"), ref("aws_kms_key.disk"))), ("ports", (443, 8443)), ("empty", ()),
        ("tags", {"ManagedBy": "opsdir", "Nested": {"a": 1}}),
        ("policy", jsonencoded({"Version": "2012-10-17", "Statement": [{"Effect": "Allow"}]})),
        ("id", ref('"${data.azurerm_resource_group.main.id}/providers/x|${var.ip}"')),
        ("chosen", ref("var.flag ? 1 : 0")),
        ("root_block_device", Block((("encrypted", True), ("ebs", Block((("size", 30),)))))))


def test_what_block_writes_reads_back_as_its_data_and_writes_again_unchanged():
    text = block("resource", ["aws_instance", "am_1"], BODY)
    (read,) = read_hcl(text)
    assert read == TfBlock("resource", ("aws_instance", "am_1"), BODY)
    assert block(read.kind, read.labels, read.body) == text


def test_a_file_is_its_comments_and_blocks_in_order():
    text = ("# Generated by opsdir\n# Do not edit.\n\n" + block("terraform", [], (
        ("required_providers", Block((("aws", {"source": "hashicorp/aws", "version": "~> 6.68"}),))),)) +
        "\n\n# NOTE: something named\n" + block("data", ["aws_vpc", "main"], (("id", "vpc-1"),)) + "\n\n" +
        block("output", ["x"], ()) + "\n")
    assert read_hcl(text) == (
        ("#", "Generated by opsdir"), ("#", "Do not edit."),
        TfBlock("terraform", (), (("required_providers", Block((("aws", {"source": "hashicorp/aws",
                                                                          "version": "~> 6.68"}),))),)),
        ("#", "NOTE: something named"), TfBlock("data", ("aws_vpc", "main"), (("id", "vpc-1"),)),
        TfBlock("output", ("x",), ()))


@pytest.mark.parametrize("text, value", [
    ('"a\\"b"', 'a"b'), ("12", 12), ("-3", -3), ("1.5", 1.5), ("false", False), ('["a", 1, x.y]', ("a", 1, "${x.y}")),
    ("[]", ()), ("tostring(var.port)", "${tostring(var.port)}"), ('"${var.a}"', '${"${var.a}"}'),
    ('"(unbalanced in a string"', "(unbalanced in a string")])
def test_values(text, value):
    assert value_of(text) == value


@pytest.mark.parametrize("text", ["[for a in var.names : upper(a)]", "[for k, v in var.tags : k if v != \"\"]",
                                  "[ for a in local.x : a ]"])
def test_a_for_expression_is_one_expression_not_a_list(text):
    body = (("names", ref(text)), ("formats", ("${format(\"%s\", x)}",)))
    assert value_of(text) == "${" + text + "}"
    written_block = block("locals", [], body)
    (read,) = read_hcl(written_block)
    assert read == TfBlock("locals", (), body)
    assert block(read.kind, read.labels, read.body) == written_block


def test_brackets_in_strings_and_comments_dont_count():
    text = '# a comment ( with { brackets\nlocals {\n  a = "]}"\n  # also ) here\n}\n'
    assert read_hcl(text) == (("#", "a comment ( with { brackets"),
                              TfBlock("locals", (), (("a", "]}"), ("#", "also ) here"))))


@pytest.mark.parametrize("text, message", [
    ('resource "x" "y" {\n  a = (1\n}\n', "line 2: unbalanced brackets: '(' is never closed"),
    ('locals {\n  a = [1, 2\n  b = "]"\n', "line 2: unbalanced brackets: '[' is never closed"),
    ('locals {\n  a = 1\n}\n}\n', "line 4: unbalanced brackets: '}' closes nothing"),
    ('resource "x" {\n  ??\n}\n', "line 2: not an attribute"),
    ("just words\n", "line 1: not a block or comment")])
def test_what_it_cannot_read_is_an_error(text, message):
    with pytest.raises(ValueError, match=re.escape(message)):
        read_hcl(text)


@pytest.mark.parametrize("text, line", [
    ('resource "x" "y" {\n  a = 1\n  ??\n}\n', 3), ('resource "x" "y" {\n  a = 1\n  tags = {\n    ??\n  }\n}\n', 4),
    ('resource "x" "y" {\n  a = 1\n  ebs {\n    ??\n  }\n}\n', 4),
    ('locals {\n  a = {\n    b = {\n      c = 1\n      ??\n    }\n  }\n}\n', 5),
    ('# head\n\nresource "x" "y" {\n  ebs {\n    t = {\n      a = 1\n      ??\n    }\n  }\n}\n', 7)])
def test_an_error_names_the_line_it_is_on_in_objects_and_nested_blocks_too(text, line):
    assert text.splitlines()[line - 1].strip() == "??"
    with pytest.raises(ValueError, match=f"^line {line}: "):
        read_hcl(text)


def test_value_of_counts_lines_from_its_own_text():
    with pytest.raises(ValueError, match="^line 4: "):
        value_of("\n{\n  a = 1\n  ??\n}")


def test_a_file_written_from_its_items_reads_back_as_them():
    items = (tf_block("terraform", [], [("required_version", ">= 1.10")]), comment("NOTE: something named"),
             tf_block("resource", ["aws_instance", "am_1"], BODY), tf_import("aws_instance.am_1", "i-0abc"))
    f = TfFile("# Generated by opsdir\n# UNBOUND: required role 'x' has no binding in this environment\n", items)
    text = hcl_file(f)
    assert text == (f.head + "\n" + block(*items[0]) + "\n\n# NOTE: something named\n\n" + block(*items[2]) +
                    '\n\nimport {\n  to = aws_instance.am_1\n  id = "i-0abc"\n}\n')
    assert read_hcl(text) == (("#", "Generated by opsdir"), ("#", "UNBOUND: required role 'x' has no binding in this "
                                                                   "environment"), *items)
    assert written({"a/main.tf": f, "a/script.py": "print()\n"}) == {"a/main.tf": text, "a/script.py": "print()\n"}
    assert hcl_item(items[3]) == 'import {\n  to = aws_instance.am_1\n  id = "i-0abc"\n}'


def test_text_is_never_an_item():
    with pytest.raises(TypeError):
        hcl_item('resource "a" "b" {\n}')
