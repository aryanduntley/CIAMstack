def test_manifest_lists_scope_and_hash_of_every_file(estate):
    m = env_model(estate["before"], "rtx-next/prod", ("backup-target",))
    doc = json.loads(manifest(m, {"b.txt": "neutral"}, {"a.txt": "specific"}))
    assert doc["environment"] == m.dn and doc["provider"] == "azure" and doc["unbound_roles"] == ["backup-target"]
    assert list(doc["files"]) == ["a.txt", "b.txt"]
    assert doc["files"]["b.txt"] == {"scope": "environment-neutral",
                                     "sha256": hashlib.sha256(b"neutral").hexdigest()}
    assert doc["files"]["a.txt"]["scope"] == "environment-specific"
    assert header(m, "what").splitlines()[0] == f"# Generated by opsdir from {m.dn}"


def test_branch_names():
    assert branch("consumers") == f"ou=consumers,{SUFFIX}"
    assert branch("declared", branch("config")) == f"ou=declared,ou=config,{SUFFIX}"


def test_registry_composition():
    assert schema_fragments()[0] is CORE
    files = sql_files()
    assert [f.name for f in files[:2]] == ["001_core.sql", "002_graph.sql"] and files[-1].name == "connectors.sql"
    assert all(f.is_file() for f in files)
    schemes = ref_schemes()
    assert len(schemes) == len(set(schemes)) and {"aws-sm", "vault"} <= set(schemes)
    assert all(a.kind in ("provider", "product", "secret-store") for a in ADAPTERS)


@pytest.mark.parametrize("uri, command", [
    ("aws-sm://prod/ds/root", "aws secretsmanager get-secret-value --secret-id 'prod/ds/root'"),
    ("azkv://kv-prod/ds-root", "az keyvault secret show --vault-name 'kv-prod' --name 'ds-root'"),
    ("vault://secret/ds/root", "vault kv get -field=value 'secret/ds/root'")])
def test_secret_references_resolve_through_the_owning_adapter(uri, command):
    assert secret_command(uri).startswith(command)


def test_unknown_secret_scheme_exits():
    with pytest.raises(SystemExit):
        secret_command("nosuch://x")


def _adapter(renders, neutral_label):
    return Adapter("x", "product", None, (), None, None, (), (), {}, renders, neutral_label)


def test_render_summary_reads_like_a_sentence():
    assert render_summary(()) == "nothing"
    assert render_summary((_adapter("Terraform", None),)) == "Terraform"
    assert render_summary((_adapter("Terraform", None), _adapter("scripts", "DS"), _adapter(None, "PF"))) == \
        "Terraform, scripts, and the environment-neutral DS/PF configuration"
