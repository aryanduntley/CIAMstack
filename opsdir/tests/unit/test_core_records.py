def test_findings_merge_concatenates_each_column_in_order():
    a = findings(blockers=[("A", "a", "o")], ok=["fine"])
    b = findings(actions=[("B", "b", "o", None)], ok=["also"], requests=[("r",)])
    assert merge_findings([a, b]) == Findings((("A", "a", "o"),), (("B", "b", "o", None),), ("fine", "also"), (("r",),))
    assert merge_findings([]) == findings()


def test_owners_come_from_the_directory(estate):
    d = estate["before"]
    owned = get(d, "env=prod,cloud=aws-current,ou=environments,dc=ciam-ops")
    unowned = get(d, "cn=legacy-rptuser,ou=consumers,dc=ciam-ops")
    assert owner_label(d, owned) == "ciam-platform"
    assert owner_label(d, unowned) == "**NO OWNER**"
    assert responsible(d, None, unowned, owned) == "ciam-platform"      # first entry that has an owner
    assert responsible(d, unowned) == "**NO OWNER**"


def test_operator_and_display_names_are_data(estate):
    d = estate["before"]
    assert display_name(get(d, "cn=ciam-platform,ou=owners,dc=ciam-ops")) == "CIAM platform team"
    assert display_name(get(d, "cn=network-security,ou=owners,dc=ciam-ops")) == "network-security"   # no display name
    assert operator(d).dn == "cn=example-aero,ou=owners,dc=ciam-ops"


