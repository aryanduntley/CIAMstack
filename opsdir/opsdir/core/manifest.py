"""Generated means generated (SPEC R10): do-not-edit headers and the MANIFEST of every rendered file."""
import hashlib
import json


def header(m, what):
    return (f"# Generated by opsdir from {m.dn}\n"
            f"# {what}\n"
            f"# Do not edit. Change the operations directory (under an approved change) and re-render.\n")


def manifest(m, neutral, specific):
    """MANIFEST.json text: environment, provider, unbound roles, each file's scope and SHA-256."""
    files = {p: {"scope": "environment-neutral" if p in neutral else "environment-specific",
                 "sha256": hashlib.sha256(c.encode()).hexdigest()}
             for p, c in sorted({**neutral, **specific}.items())}
    return json.dumps({"environment": m.dn, "provider": m.provider, "unbound_roles": list(m.unbound),
                       "files": files}, indent=2) + "\n"
