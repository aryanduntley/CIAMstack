#!/usr/bin/env python3
"""Generate opsdir/domains/observability/attack_table.py: MITRE ATT&CK Enterprise as the core's alert rules record it.

Reads MITRE's STIX 2.1 bundle of a release (github.com/mitre-attack/attack-stix-data,
enterprise-attack/enterprise-attack-<version>.json: downloaded, or a local copy with --bundle) and writes its tactics
(short name -> ID, name; the matrix's order), its techniques and sub-techniques neither revoked nor deprecated (ID ->
name, the tactics each serves), and the technique IDs it retired (ID -> name, revoked or deprecated, the live
techniques a revoked one was replaced by, its revoked-by relationships followed to a live one). A tactic short name a
release retired isn't in the bundle (a tactic keeps its ID, its short name changes): RETIRED_TACTICS below says which
and what replaced it, from MITRE's release notes, and the script checks it against the bundle. Commit the module: the
core and the SIEM adapters read it, never the bundle.

Usage: gen-attack.py [--version 20.0] [--bundle path/to/enterprise-attack-20.0.json]
"""
import argparse
import json
import pathlib
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "opsdir" / "domains" / "observability" / "attack_table.py"
VERSION = "20.0"
SOURCE = "https://raw.githubusercontent.com/mitre-attack/attack-stix-data/master/enterprise-attack/"
# Tactic short names a release retired: short name -> (its ID, its name then, the short names replacing it). ATT&CK
# v19 (attack.mitre.org/resources/updates/updates-april-2026/) split Defense Evasion: TA0005 became Stealth and
# Defense Impairment (TA0112) was added.
RETIRED_TACTICS = {"defense-evasion": ("TA0005", "Defense Evasion", ("stealth", "defense-impairment"))}
WIDTH = 120

HEADER = '''"""MITRE ATT&CK Enterprise v{version}: its tactics, techniques and the technique IDs it retired.
GENERATED by opsdir/scripts/gen-attack.py from MITRE's STIX bundle (github.com/mitre-attack/attack-stix-data,
enterprise-attack/enterprise-attack-{version}.json): don't edit, regenerate. Read through observability.attack."""

ATTACK_VERSION = "{version}"
# tactic short name -> (ID, name), in the matrix's order
'''


def external_id(o):
    """The ATT&CK ID (T1110, TA0006) of a STIX object, or None."""
    return next((r["external_id"] for r in o.get("external_references", ()) if r.get("source_name") == "mitre-attack"),
                None)


def is_live(o):
    return not o.get("revoked") and not o.get("x_mitre_deprecated")


def _order(tid):
    return tuple(int(x) for x in tid[1:].split("."))


def tactics(objects):
    """[(short name, ID, name), ...] of the bundle's live tactics, in the matrix's order."""
    live = {o["id"]: o for o in objects if o["type"] == "x-mitre-tactic" and is_live(o)}
    matrix = next(o for o in objects if o["type"] == "x-mitre-matrix" and is_live(o))
    return [(live[r]["x_mitre_shortname"], external_id(live[r]), live[r]["name"]) for r in matrix["tactic_refs"]]


def techniques(objects):
    """{ID: (name, (tactic short names, ...))} of the bundle's live techniques and sub-techniques, in ID order."""
    live = [(external_id(o), o) for o in objects if o["type"] == "attack-pattern" and is_live(o) and external_id(o)]
    return {tid: (o["name"], tuple(k["phase_name"] for k in o.get("kill_chain_phases", ())
                                   if k.get("kill_chain_name") == "mitre-attack"))
            for tid, o in sorted(live, key=lambda p: _order(p[0]))}


def retired(objects, live):
    """{ID: (name, 'revoked' | 'deprecated', (live replacing IDs, ...))} of technique IDs the bundle holds only
    retired, a revoked one's revoked-by relationships followed until a live technique (none: no replacement)."""
    by_id = {o["id"]: o for o in objects}
    revoked_by = {}
    for r in objects:
        if r["type"] == "relationship" and r.get("relationship_type") == "revoked-by" and is_live(r):
            revoked_by.setdefault(r["source_ref"], []).append(r["target_ref"])

    def replacing(ref, seen=()):
        o = by_id.get(ref)
        if o is None or ref in seen:
            return ()
        if is_live(o):
            return (external_id(o),)
        return tuple(x for t in revoked_by.get(ref, ()) for x in replacing(t, (*seen, ref)))
    gone = {}
    for o in objects:
        tid = external_id(o) if o["type"] == "attack-pattern" else None
        if tid and tid not in live and (o.get("revoked") or o.get("x_mitre_deprecated")):
            kind = "revoked" if o.get("revoked") else "deprecated"
            found = tuple(dict.fromkeys(x for t in revoked_by.get(o["id"], ()) for x in replacing(t)))
            if tid not in gone or (kind == "revoked" and found):
                gone[tid] = (o["name"], kind, found)
    return {tid: gone[tid] for tid in sorted(gone, key=_order)}


def _line(head, parts):
    """A dict entry line, its value wrapped under the key when it would be wider than WIDTH."""
    line = f"    {head}: ({', '.join(parts)}),"
    if len(line) <= WIDTH:
        return line
    return f"    {head}: ({parts[0]},\n{' ' * (len(head) + 7)}{', '.join(parts[1:])}),"


def _strs(items):
    return "(" + ", ".join(json.dumps(x) for x in items) + ("," if len(items) == 1 else "") + ")"


def module_text(version, objects):
    """The attack_table module of a release's bundle."""
    found = tactics(objects)
    shorts = {s for s, _, _ in found}
    for old, (tid, _, new) in RETIRED_TACTICS.items():
        assert old not in shorts and set(new) <= shorts, f"RETIRED_TACTICS {old} doesn't match the bundle"
        assert any(t == tid for _, t, _ in found), f"RETIRED_TACTICS {old}: {tid} isn't in the bundle"
    live = techniques(objects)
    gone = retired(objects, live)
    lines = [HEADER.format(version=version) + "TACTICS = {",
             *(f"    {json.dumps(s)}: ({json.dumps(t)}, {json.dumps(n)})," for s, t, n in found), "}",
             "# tactic short names it retired -> (their ID, their name then, the short names replacing them)",
             "RETIRED_TACTICS = {",
             *(f"    {json.dumps(s)}: ({json.dumps(t)}, {json.dumps(n)}, {_strs(new)})," for s, (t, n, new)
               in RETIRED_TACTICS.items()), "}",
             "# technique or sub-technique ID -> (name, the tactics it serves: short names)", "TECHNIQUES = {",
             *(_line(json.dumps(tid), [json.dumps(n), _strs(ts)]) for tid, (n, ts) in live.items()), "}",
             "# technique IDs it retired -> (name, revoked or deprecated, the techniques replacing a revoked one)",
             "RETIRED = {",
             *(_line(json.dumps(tid), [json.dumps(n), json.dumps(k), _strs(new)]) for tid, (n, k, new) in gone.items()),
             "}"]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--version", default=VERSION, help="the ATT&CK release (default %(default)s)")
    parser.add_argument("--bundle", help="a local copy of the release's STIX bundle (else downloaded)")
    args = parser.parse_args()
    if args.bundle:
        raw = pathlib.Path(args.bundle).read_bytes()
    else:
        with urllib.request.urlopen(f"{SOURCE}enterprise-attack-{args.version}.json", timeout=120) as r:
            raw = r.read()
    objects = json.loads(raw)["objects"]
    OUT.write_text(module_text(args.version, objects))
    print(len(tactics(objects)), "tactics", len(techniques(objects)), "techniques", "->", OUT)


if __name__ == "__main__":
    main()
